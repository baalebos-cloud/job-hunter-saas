BRANDING = ['Baalebos', 'Powered by', 'Generated by', 'Created with', 'Resume.io', 'Page 1 of', 'ATS Improvement Notes',
            'Canva', 'Zety', 'AI-optimized', 'ReportLab', 'reportlab.com']


def text_of(pdf):
    with pdfplumber.open(io.BytesIO(pdf)) as doc:
        return '\n'.join(page.extract_text() or '' for page in doc.pages)


@pytest.mark.parametrize('raw,expected', [
    ('Senior Software Engineer | Powered by Baalebos Cloud', 'Senior Software Engineer'),
    ('React developer • Generated by ChatGPT • Lagos', 'React developer • Lagos'),
    ('Jane Doe | jane@example.com | resume.io', 'Jane Doe | jane@example.com'),
    ('Created with Canva', ''),
    ('Resume template by Zety', ''),
    ('Page 2 of 3', ''),
    ('ATS Improvement Notes: add Terraform to skills', ''),
    ('Add Terraform and Kubernetes to your skills section', ''),
    ('Built CI pipelines using Jenkins', 'Built CI pipelines using Jenkins'),
    ('Designed marketing assets with Canva', 'Designed marketing assets with Canva'),
    ('Led R&D on <5s cold starts', 'Led R&D on <5s cold starts'),
    # The product's bare name is a watermark only as a whole line; beside other
    # content it is a candidate's own project.
    ('Baalebos AI', ''),
    ('Baalebos Cloud', ''),
    ('Baalebos AI | Multi-provider LLM gateway', 'Baalebos AI | Multi-provider LLM gateway'),
])
def test_strip_watermarks_preserves_candidate_content(raw, expected):
    assert strip_watermarks_and_branding(raw) == expected


def test_no_branding_reaches_any_rendered_field_or_pdf_bytes():
    data = {
        'name': 'Ada Obi | Powered by Baalebos Cloud', 'title': 'Data Engineer • Created with Canva',
        'contact': 'ada@example.com | Page 1 of 2 | Resume.io',
        'summary': 'Data engineer. ATS Improvement Notes: add Spark.',
        'experience': [{'role': 'Data Engineer | Generated by ChatGPT', 'company': 'Acme', 'dates': '2021 - Present',
                        'bullets': ['Built ETL in Python | AI-optimized resume', 'Page 1 of 2']}],
        'skills': {'Skills': ['Python', 'Resume template by Zety']},
        'education': [{'degree': 'BSc', 'institution': 'Unilag', 'year': '2019'}],
        'additional_information': 'Optimized by Baalebos Cloud AI',
    }
    result = export_resume(data, region='NG')
    text = text_of(result.pdf)
    for marker in BRANDING:
        assert marker.lower() not in text.lower(), marker
        assert marker.encode().lower() not in result.pdf.lower(), marker
    for real in ('Ada Obi', 'Data Engineer', 'ada@example.com', 'Built ETL in Python', 'Acme', 'BSc'):
        assert real in text
    metadata = PdfReader(io.BytesIO(result.pdf)).metadata
    assert metadata['/Title'] == 'Ada Obi - Resume' and not metadata.get('/Producer') and not metadata.get('/Creator')


def huge_resume(roles=8, bullets=7):
    return {
        'name': 'Big Candidate', 'contact': 'big@example.com | Lagos, Nigeria',
        'summary': 'Platform engineer with a long career. ' * 10,
        'experience': [{'role': f'Engineer {i}', 'company': f'Company {i}', 'dates': f'Jan {2010 + i} - Dec {2011 + i}',
                        'environment': 'Python, AWS, Terraform',
                        'bullets': [f'Delivered Python platform improvement {j} for team {i} with reviews and runbooks.'
                                    for j in range(bullets)]} for i in range(roles)],
        'projects': [{'title': f'Project {i}', 'tech': 'Go', 'bullets': ['Built it.', 'Ran it.', 'Documented it.']}
                     for i in range(4)],
        'skills': {'Cloud': ['AWS', 'Terraform'], 'Languages': ['Python', 'Go']},
        'education': [{'degree': 'BSc Physics', 'institution': 'University of Lagos', 'year': '2009'},
                      {'degree': 'MSc Computing', 'institution': 'University of Ibadan', 'year': '2012'}],
        'certifications': [f'Certification {i}' for i in range(6)],
    }


@pytest.mark.parametrize('region', ['NG', 'US'])
def test_strict_one_page_keeps_protected_facts(region):
    data = huge_resume()
    result = export_resume(data, region=region, priority_keywords=['Python'])
    assert len(PdfReader(io.BytesIO(result.pdf)).pages) == 1 == result.pages
    assert result.condensed and result.layout == 'compact'
    # Condense order: secondary content before experience bullets.
    assert result.condensed_items[0].startswith('Removed tool lists')
    assert any(item.startswith('Shortened summary') for item in result.condensed_items)
    text = text_of(result.pdf)
    for job in data['experience']:
        assert job['role'] in text and job['company'] in text and job['dates'] in text
    for edu in data['education']:
        assert edu['degree'] in text
    for cert in data['certifications']:
        assert cert in text
    assert any('one page' in w for w in result.warnings)


def test_layout_profiles_fit_before_trimming():
    data = huge_resume(roles=3, bullets=5)
    result = export_resume(data)
    assert result.pages == 1
    assert result.layout in ('standard', 'balanced', 'compact')
    if result.layout != 'compact':
        assert not result.condensed


def test_oldest_role_loses_bullets_first():
    data = huge_resume(roles=5, bullets=6)
    data['summary'] = 'Engineer.'
    data['projects'] = []
    for job in data['experience']:
        job['environment'] = ''
    # Experience is reverse-chronological: Engineer 0 is the most recent.
    result = export_resume(data)
    text = text_of(result.pdf)
    recent = sum(f'team 0 ' in line for line in text.splitlines())
    oldest = sum(f'team 4 ' in line for line in text.splitlines())
    assert recent >= oldest


def test_unfittable_resume_is_rejected_not_truncated():
    data = huge_resume()
    data['certifications'] = [f'Certification number {i} with a long official title' for i in range(150)]
    with pytest.raises(ResumeExportError, match='one page'):
        export_resume(data)


def test_reportlab_markup_injection_is_neutralised():
    data = huge_resume(roles=1, bullets=2)
    data['experience'][0]['bullets'] = ['<font size="40" color="red">HUGE</font> <para>x</para> <script>alert(1)</script>Built APIs',
                                        '/JavaScript (app.alert(1)) 1 0 obj Shipped <5s deploys with R&D']
    result = export_resume(data)
    with pdfplumber.open(io.BytesIO(result.pdf)) as doc:
        page = doc.pages[0]
        assert max(c['size'] for c in page.chars) <= 16
        text = page.extract_text()
    assert 'HUGE' in text and 'Built APIs' in text and 'alert(1)' not in text.replace('(app.alert(1))', '')
    assert '/JavaScript' not in text and 'Shipped <5s deploys with R&D' in text
    assert b'/JavaScript' not in result.pdf and b'/OpenAction' not in result.pdf


def test_sanitize_untrusted_text():
    report = sanitize_untrusted_text('Hi <script>steal()</script><para>there</para> /OpenAction <5s', report=True)
    assert report.text == 'Hi there <5s' and report.blocked >= 3
    assert sanitize_untrusted_text('ﬁle​') == 'file'
    # Compatibility folding keeps superscripts and subscripts: they carry meaning.
    assert sanitize_untrusted_text('Reported R² 0.662; cut CO₂ by 10³ t; ＡＷＳ') == 'Reported R² 0.662; cut CO₂ by 10³ t; AWS'


