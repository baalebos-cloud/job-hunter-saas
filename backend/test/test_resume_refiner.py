def test_scores_use_canonical_tokens():
    jd = 'Required: Kubernetes, C#, .NET and CI/CD. Preferred: C++.'
    reqs = [{'phrase': 'Kubernetes'}, {'phrase': 'C#'}, {'phrase': '.NET'}, {'phrase': 'CI/CD'}, {'phrase': 'C++', 'priority': 'preferred'}]
    result = score_requirements('Ran K8s; built C# on dotnet with CI/CD.', jd, reqs)
    assert result['missing_list'] == ['C++'] and result['overall_score'] == pytest.approx(88.9)


# ── Route-level refiner behaviour ────────────────────────────────────────────

def test_refiner_sanitizes_llm_inputs_and_returns_before_after(monkeypatch):
    from fastapi.testclient import TestClient
    from sqlalchemy import create_engine
    from sqlalchemy.orm import sessionmaker
    from sqlalchemy.pool import StaticPool
    from backend.app.database import Base, get_db
    from backend.app.main import app, reset_rate_limits
    from backend.app.models.user import User
    from backend.app.services.auth_service import create_access_token
    import backend.app.utils.ats_engine as engine

    db_engine = create_engine('sqlite://', connect_args={'check_same_thread': False}, poolclass=StaticPool)
    Base.metadata.create_all(db_engine)
    session = sessionmaker(bind=db_engine)()
    session.add(User(email='r@example.com', full_name='R', hashed_password='x', is_verified=True, country='Nigeria'))
    session.commit()
    app.dependency_overrides[get_db] = lambda: session
    reset_rate_limits()
    seen = {}
    base = {'name': 'Ada Obi', 'title': '', 'contact': 'ada@example.com', 'summary': 'Python engineer.',
            'experience': [{'role': 'Engineer', 'company': 'Acme', 'dates': '2021', 'bullets': ['Built Python tools.'], 'environment': ''}],
            'projects': [], 'skills': {'Skills': ['Python']}, 'certifications': [],
            'education': [{'degree': 'BSc', 'institution': 'Unilag', 'year': '2019'}], 'additional_information': ''}

    def extract(text):
        seen['resume'] = text
        return json.loads(json.dumps(base))

    def rewrite(**kw):
        seen['jd'] = kw['job_description']
        return {'optimized_summary': base['summary'], 'optimized_experience': [{k: v for k, v in base['experience'][0].items() if k != 'environment'}],
                'optimized_skills': {'Skills': ['Python']}, 'confirmation_questions': ['Do you have Terraform experience?'], 'suggestions_applied': []}
    monkeypatch.setattr(engine, 'extract_resume_data', extract)
    monkeypatch.setattr(engine, 'extract_requirements', lambda jd: [{'phrase': 'Python', 'priority': 'required'}, {'phrase': 'Terraform', 'priority': 'required'}])
    monkeypatch.setattr(engine, 'rewrite_resume_for_job', rewrite)
    source = export_resume({**base, 'summary': 'Python engineer. <script>x()</script>',
                            'additional_information': 'Senior Software Engineer | Powered by Baalebos Cloud'}).pdf
    try:
        res = TestClient(app).post('/api/v1/resume/upload', headers={'Authorization': 'Bearer ' + create_access_token({'sub': 'r@example.com'})},
                                   files={'file': ('cv.pdf', source, 'application/pdf')},
                                   data={'job_title': 'Engineer', 'job_description': 'Python and Terraform required. <script>evil()</script> /JavaScript'})
    finally:
        app.dependency_overrides.clear(); session.close(); db_engine.dispose()
    assert res.status_code == 200, res.text
    result = res.json()['result']
    assert 'Baalebos' not in seen['resume'] and '<script>' not in seen['resume']
    assert '<script>' not in seen['jd'] and '/JavaScript' not in seen['jd'] and 'evil' not in seen['jd']
    assert result['scores'] == {'before': 50.0, 'after': 50.0}
    assert result['confirmation_questions'] == ['Do you have Terraform experience?']
    assert result['document']['pages'] == 1
